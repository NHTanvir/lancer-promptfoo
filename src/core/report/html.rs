//! Self-contained HTML report dashboard (severity summary + findings table +
//! per-finding detail). No external assets — inline CSS only.

use crate::core::report::xml::xml_escape;
use crate::core::types::{RedteamReport, Severity};
use std::fmt::Write as _;

fn sev_color(s: &Severity) -> &'static str {
    match s {
        Severity::Critical => "#b00020",
        Severity::High => "#e64a19",
        Severity::Medium => "#f9a825",
        Severity::Low => "#9e9d24",
        Severity::Informational => "#607d8b",
    }
}

pub fn render(report: &RedteamReport) -> String {
    let s = &report.summary;
    let mut out = String::new();
    let _ = write!(
        out,
        r#"<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>lancer-promptfoo report: {target}</title>
<style>
body{{font-family:-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#0f1115;color:#e6e6e6}}
header{{padding:24px 32px;background:#161a22;border-bottom:1px solid #262b36}}
h1{{margin:0;font-size:20px}} .sub{{color:#8a93a6;font-size:13px;margin-top:4px}}
.cards{{display:flex;gap:12px;padding:24px 32px;flex-wrap:wrap}}
.card{{background:#161a22;border:1px solid #262b36;border-radius:10px;padding:14px 18px;min-width:110px}}
.card .n{{font-size:26px;font-weight:700}} .card .l{{font-size:12px;color:#8a93a6;text-transform:uppercase;letter-spacing:.05em}}
table{{width:calc(100% - 64px);margin:0 32px 32px;border-collapse:collapse;background:#161a22;border-radius:10px;overflow:hidden}}
th,td{{text-align:left;padding:10px 12px;border-bottom:1px solid #262b36;font-size:13px;vertical-align:top}}
th{{background:#1b2029;color:#8a93a6;text-transform:uppercase;font-size:11px;letter-spacing:.05em}}
.badge{{display:inline-block;padding:2px 8px;border-radius:10px;color:#fff;font-size:11px;font-weight:700}}
details{{margin:0 32px 8px}} summary{{cursor:pointer;color:#7aa2f7}}
pre{{background:#0b0d12;border:1px solid #262b36;border-radius:8px;padding:10px;overflow:auto;font-size:12px;white-space:pre-wrap}}
.pass{{color:#3fb950}} .fail{{color:#f85149}}
</style></head><body>
<header><h1>LLM Red Team Report — {target}</h1>
<div class="sub">Generated by lancer-promptfoo · {time}{purpose}</div></header>
<div class="cards">
  <div class="card"><div class="n">{total}</div><div class="l">Tests</div></div>
  <div class="card"><div class="n">{rate:.1}%</div><div class="l">Pass rate</div></div>
  <div class="card"><div class="n" style="color:{cc}">{crit}</div><div class="l">Critical</div></div>
  <div class="card"><div class="n" style="color:{hc}">{high}</div><div class="l">High</div></div>
  <div class="card"><div class="n" style="color:{mc}">{med}</div><div class="l">Medium</div></div>
  <div class="card"><div class="n" style="color:{lc}">{low}</div><div class="l">Low</div></div>
  <div class="card"><div class="n">{info}</div><div class="l">Info</div></div>
</div>
"#,
        target = xml_escape(&report.target),
        time = report.timestamp.format("%Y-%m-%d %H:%M UTC"),
        purpose = report
            .purpose
            .as_deref()
            .map(|p| format!(" · {}", xml_escape(p)))
            .unwrap_or_default(),
        total = s.total_tests,
        rate = s.pass_rate * 100.0,
        crit = s.critical,
        high = s.high,
        med = s.medium,
        low = s.low,
        info = s.informational,
        cc = sev_color(&Severity::Critical),
        hc = sev_color(&Severity::High),
        mc = sev_color(&Severity::Medium),
        lc = sev_color(&Severity::Low),
    );

    let mut findings = report.findings();
    findings.sort_by(|a, b| a.severity.cmp(&b.severity));

    let _ = write!(
        out,
        "<table><thead><tr><th>Severity</th><th>Plugin</th><th>Strategy</th><th>Score</th><th>Title</th></tr></thead><tbody>"
    );
    for v in &findings {
        let _ = write!(
            out,
            "<tr><td><span class=\"badge\" style=\"background:{}\">{}</span></td><td>{}</td><td>{}</td><td>{:.2}</td><td>{}</td></tr>",
            sev_color(&v.severity),
            v.severity.label(),
            xml_escape(&v.plugin),
            xml_escape(v.strategy.as_deref().unwrap_or("-")),
            v.score,
            xml_escape(&v.title),
        );
    }
    let _ = write!(out, "</tbody></table>");

    if findings.is_empty() {
        let _ = write!(out, "<p style=\"margin:0 32px 32px\" class=\"pass\">✓ No exploitable vulnerabilities found.</p>");
    }

    // Detail drawers for each finding.
    for v in &findings {
        let _ = write!(
            out,
            "<details><summary>[{}] {} — {}</summary><pre>Attack:\n{}\n\nResponse:\n{}\n\nReason: {}</pre></details>",
            v.severity.label(),
            xml_escape(&v.plugin),
            xml_escape(&v.title),
            xml_escape(&v.attack_prompt),
            xml_escape(&v.model_response.chars().take(4000).collect::<String>()),
            xml_escape(&v.description),
        );
    }

    let _ = write!(out, "</body></html>");
    out
}
