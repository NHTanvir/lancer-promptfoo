//! Markdown bounty-report renderer.

use crate::core::types::{RedteamReport, Severity, Vulnerability};
use anyhow::{Context, Result};
use std::fmt::Write as _;
use std::path::Path;

pub fn write_markdown(report: &RedteamReport, path: &Path) -> Result<()> {
    std::fs::write(path, render(report))
        .with_context(|| format!("Failed to write Markdown report to {}", path.display()))
}

pub fn render(report: &RedteamReport) -> String {
    let mut out = String::new();
    let s = &report.summary;
    let _ = writeln!(out, "# LLM Red Team Report: {}\n", report.target);
    let _ = writeln!(
        out,
        "_Generated by lancer-promptfoo on {}_\n",
        report.timestamp.format("%Y-%m-%d %H:%M UTC")
    );
    if let Some(p) = &report.purpose {
        let _ = writeln!(out, "**Target purpose:** {}\n", p);
    }
    if !report.tags.is_empty() {
        let _ = writeln!(out, "**Tags:** {}\n", report.tags.join(", "));
    }

    let _ = writeln!(out, "## Executive Summary\n");
    let _ = writeln!(out, "| Metric | Value |\n|--------|-------|");
    let _ = writeln!(out, "| Total tests | {} |", s.total_tests);
    let _ = writeln!(out, "| Pass rate | {:.1}% |", s.pass_rate * 100.0);
    let _ = writeln!(out, "| CRITICAL | {} |", s.critical);
    let _ = writeln!(out, "| HIGH | {} |", s.high);
    let _ = writeln!(out, "| MEDIUM | {} |", s.medium);
    let _ = writeln!(out, "| LOW | {} |", s.low);
    let _ = writeln!(out, "| INFO | {} |\n", s.informational);

    let findings = report.findings();
    if findings.is_empty() {
        let _ = writeln!(out, "**No exploitable vulnerabilities found.**\n");
        return out;
    }

    let mut sorted = findings.clone();
    sorted.sort_by(|a, b| a.severity.cmp(&b.severity));

    let _ = writeln!(out, "## Findings\n");
    let _ = writeln!(out, "| # | Severity | Plugin | Strategy | Score |");
    let _ = writeln!(out, "|---|----------|--------|----------|-------|");
    for (i, v) in sorted.iter().enumerate() {
        let _ = writeln!(
            out,
            "| {} | {} | `{}` | {} | {:.2} |",
            i + 1,
            v.severity.label(),
            v.plugin,
            v.strategy.as_deref().unwrap_or("-"),
            v.score
        );
    }

    let critical_high: Vec<&&Vulnerability> = sorted
        .iter()
        .filter(|v| matches!(v.severity, Severity::Critical | Severity::High))
        .collect();
    if !critical_high.is_empty() {
        let _ = writeln!(out, "\n## Critical / High Detail\n");
        for (i, v) in critical_high.iter().enumerate() {
            let _ = writeln!(out, "### {}. [{}] {}\n", i + 1, v.severity.label(), v.plugin);
            let _ = writeln!(out, "**{}**\n", v.title);
            let _ = writeln!(out, "{}\n", v.description);
            let _ = writeln!(out, "**Attack prompt:**\n\n```\n{}\n```\n", v.attack_prompt);
            let resp: String = v.model_response.chars().take(2000).collect();
            let _ = writeln!(out, "**Model response:**\n\n```\n{}\n```\n", resp);
            let _ = writeln!(out, "**Steps to reproduce:**\n");
            let _ = writeln!(out, "1. Send the attack prompt above to the target endpoint.");
            let _ = writeln!(out, "2. Observe the target complied rather than refusing.");
            let _ = writeln!(out, "3. See `http-history.jsonl` for the full request/response capture.\n");
            let _ = writeln!(out, "**Remediation:** {}\n", remediation_advice(&v.plugin));
        }
    }

    let _ = writeln!(out, "## Methodology\n");
    let _ = writeln!(
        out,
        "Attacks were generated and graded by lancer-promptfoo's native red-team \
         engine (157+ plugins × 30+ strategies), with an LLM-as-judge grading each response."
    );
    out
}

pub fn remediation_advice(plugin: &str) -> String {
    let p = plugin.to_lowercase();
    if p.contains("prompt-injection") || p.contains("system-prompt") {
        "Add a system-prompt guardrail layer and validate responses with a separate judge model before returning them.".into()
    } else if p.contains("sql-injection") {
        "Use parameterised queries / an ORM. Never build SQL from user-controlled data.".into()
    } else if p.contains("ssrf") {
        "Validate and allowlist outbound URLs; block internal/metadata IP ranges.".into()
    } else if p.contains("pii") {
        "Audit training data for PII and add output filtering to redact PII patterns.".into()
    } else if p.contains("bola") || p.contains("bfla") || p.contains("rbac") {
        "Enforce resource-level authorisation at the API layer — never let the model infer permissions.".into()
    } else if p.contains("hallucination") {
        "Add a RAG/citation grounding layer and factuality assertions in production.".into()
    } else if p.contains("data-exfil") || p.contains("secret") || p.contains("sandbox") {
        "Restrict the agent's tool/file/env access and sandbox all reads/writes.".into()
    } else {
        "Review safety training, add refusal patterns, and add output filtering for this vulnerability class.".into()
    }
}
