//! Runtime traits and static `*Spec` descriptors.
//!
//! The big enumerated catalogs (157 plugins, ~50 providers, 30+ strategies,
//! ~40 assertions, framework presets) are expressed as **const `*Spec` tables**
//! rather than 157 hand-written impls. This is the same shape upstream uses
//! (plugins are "prompt templates + grading rubrics") and keeps the registries
//! pure data — easy to enumerate exhaustively, cheap to verify "none dropped".

use crate::core::types::{
    AssertionConfig, AssertionOutcome, CallContext, Modality, ProviderResponse, Severity, TestCase,
};
use anyhow::Result;
use async_trait::async_trait;

// ===========================================================================
// Providers
// ===========================================================================

/// Coarse provider classification, used to pick the right transport/factory.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProviderKind {
    /// Hosted chat/completion LLM behind a known REST API (OpenAI, Anthropic…).
    Chat,
    /// Generic user-supplied HTTP/HTTPS endpoint.
    Http,
    /// WebSocket endpoint.
    WebSocket,
    /// Embedding model.
    Embedding,
    /// Image generation.
    Image,
    /// Audio (speech / voice agent).
    Audio,
    /// Text-to-video.
    Video,
    /// Local script (python / javascript / ruby file).
    Script,
    /// Model Context Protocol server target.
    Mcp,
    /// Browser automation (Playwright/Chromium).
    Browser,
    /// Webhook.
    Webhook,
    /// Aggregator / gateway (litellm, openrouter, vercel-ai-gateway…).
    Gateway,
}

/// Static descriptor for one provider family. The registry is a table of these.
#[derive(Debug, Clone, Copy)]
pub struct ProviderSpec {
    /// Canonical id prefix, e.g. `"openai"`, `"anthropic"`, `"http"`, `"mlflow"`.
    pub id: &'static str,
    pub kind: ProviderKind,
    pub label: &'static str,
    /// Environment variables consulted for credentials.
    pub env_keys: &'static [&'static str],
    /// Modalities this provider can target.
    pub modalities: &'static [Modality],
    /// Alternate / legacy ids accepted by the loader.
    pub aliases: &'static [&'static str],
    pub notes: &'static str,
}

/// Live provider — issues a call and returns a response. Object-safe via
/// `async_trait` so the registry can hold `Arc<dyn Provider>`.
#[async_trait]
pub trait Provider: Send + Sync {
    fn id(&self) -> &str;
    async fn call(&self, prompt: &str, ctx: &CallContext) -> Result<ProviderResponse>;
    fn modality(&self) -> Modality {
        Modality::Text
    }
}

